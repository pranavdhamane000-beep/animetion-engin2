#Requires -Version 5.1
<#
.SYNOPSIS
    Installs the pre-commit gate into this clone's .git/hooks directory.

.DESCRIPTION
    Nothing else in this repository enforces that the gate ran. The spec's package
    rule ("a package with no commit is not finished") and this project's habit of
    trusting a green summary have both already been shown to be insufficient - the
    WP00 commit was made with spec 9.5 step 2 unmet and reported as passed anyway.
    A hook is the difference between a gate you are told to run and a gate that runs.

    .git/hooks is inside the git directory and is therefore NOT versioned, which is
    why the hook is generated from this script rather than committed as a file. Any
    fresh clone runs `tools\install-git-hooks.cmd` once, or nothing enforces anything.

    The hook runs the code gate only - fmt, clippy, test. The platform probes are
    excluded on purpose: they take ~50s, and spec 9.12 makes their validity a
    function of this specific adapter and driver, so they belong at re-certification
    time (tools\ci.ps1 -WithProbes), not on every commit.

.NOTES
    Line endings matter: the hook is a /bin/sh script, and Git for Windows' sh
    rejects a CRLF-terminated shebang. The file is written with explicit LF and no
    BOM. That is the whole reason this is a script instead of a committed file you
    can open and edit in place - an editor on Windows will silently convert it.

    The gate inspects the working tree, not the staged diff (cargo fmt and cargo
    clippy do not operate on a staged snapshot). Committing a subset of local
    changes therefore validates more than you are committing, not less. That is the
    safe direction, and it is why the gate runs on the whole workspace.
#>
[CmdletBinding()]
param(
    [switch]$Force
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path -Parent $PSScriptRoot
$GitDir = Join-Path $RepoRoot '.git'
if (-not (Test-Path -LiteralPath $GitDir)) {
    # A worktree keeps its gitdir elsewhere. Refuse rather than write a hook into
    # the wrong place, because a hook that is not installed is silently identical
    # to no hook at all.
    throw "no .git directory at $RepoRoot - run this from the repository root"
}

$HookPath = Join-Path (Join-Path $GitDir 'hooks') 'pre-commit'
$HookDir = Split-Path -Parent $HookPath
if (-not (Test-Path -LiteralPath $HookDir)) {
    New-Item -ItemType Directory -Path $HookDir -Force | Out-Null
}

if ((Test-Path -LiteralPath $HookPath) -and -not $Force) {
    $existing = Get-Content -LiteralPath $HookPath -Raw
    if ($existing -match 'ci\.ps1') {
        Write-Host "pre-commit hook already installed and references the gate:" -ForegroundColor Green
        Write-Host "  $HookPath" -ForegroundColor DarkGray
        Write-Host 'Re-run with -Force to rewrite it.' -ForegroundColor DarkGray
        exit 0
    }
    throw "a pre-commit hook exists at $HookPath but does not run the gate. Inspect it, then re-run with -Force to replace it."
}

# ---------------------------------------------------------------------------
# The hook body. Written with LF explicitly; see the .NOTES above.
# ---------------------------------------------------------------------------
$Hook = @'
#!/bin/sh
# Generated by tools/install-git-hooks.ps1 - do not edit in place; edit the script.
#
# Spec 9.5 step 2 requires warnings-as-errors enforced. Without this hook the gate
# is a suggestion, and a suggestion has already been missed once on this project.
#
# Bypass deliberately with:  git commit --no-verify
# Doing that is a visible choice, which is the point - it should not be the default.

set -u

repo_root=$(git rev-parse --show-toplevel) || {
    echo "pre-commit: cannot locate repository root." >&2
    exit 1
}
gate="$repo_root/tools/ci.ps1"

if [ ! -f "$gate" ]; then
    echo "pre-commit: gate script missing at $gate" >&2
    echo "            Refusing to commit: an absent gate is indistinguishable from" >&2
    echo "            a passing one, and that confusion is exactly what this hook" >&2
    echo "            exists to prevent." >&2
    exit 1
fi

if command -v powershell.exe >/dev/null 2>&1; then
    pwsh_shell='powershell.exe'
elif command -v pwsh >/dev/null 2>&1; then
    pwsh_shell='pwsh'
else
    echo "pre-commit: no PowerShell found; cannot run the gate." >&2
    exit 1
fi

echo "pre-commit: running the workspace gate (fmt, clippy -D warnings, test --locked)"

"$pwsh_shell" -NoProfile -ExecutionPolicy Bypass -File "$gate"
code=$?

if [ $code -ne 0 ]; then
    echo "" >&2
    echo "pre-commit: BLOCKED (gate exit $code)." >&2
    echo "            Fix what failed, or bypass knowingly with --no-verify." >&2
    exit $code
fi

echo "pre-commit: gate green."
exit 0
'@

# LF only, no BOM. `n is LF on every platform in PowerShell strings here.
[System.IO.File]::WriteAllText($HookPath, $Hook.Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding($false)))

Write-Host "installed: $HookPath" -ForegroundColor Green
Write-Host 'verify with: git config core.hooksPath  (unset means .git/hooks is in use)' -ForegroundColor DarkGray

# If core.hooksPath is set, .git/hooks is ignored and this install silently does
# nothing - the worst outcome, because it looks like protection. Warn loudly.
$hooksPath = (& git -C $RepoRoot config --get core.hooksPath 2>$null)
if ($hooksPath) {
    Write-Host ''
    Write-Host "WARNING: core.hooksPath is set to '$hooksPath'." -ForegroundColor Yellow
    Write-Host '         Git will ignore the hook just installed. Either unset it' -ForegroundColor Yellow
    Write-Host '         (git config --unset core.hooksPath) or install the hook there.' -ForegroundColor Yellow
}
